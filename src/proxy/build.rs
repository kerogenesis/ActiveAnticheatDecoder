//! One binary stands in for ddraw, d3d9 or xinput1_4.
//! Pre-built export table (ForwardN/OrdinalN/SharedN stubs + /EXPORT
//! aliases, stub space reused per DLL as Forward{ordinal - base}) lets the
//! loader accept any of the three names. Tables are dumpbin snapshots of the
//! 32-bit originals; distinct stub immediates defeat /OPT:ICF folding.

use std::collections::BTreeSet;
use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

const NAMED_SLOTS: u16 = 23;
const MAX_ORDINAL: u16 = 109;

// The same three names live in proxy.rs SHARED; change both.
const SHARED: &[&str] = &["DllCanUnloadNow", "DllGetClassObject", "SetAppCompatStringPointer"];

const DDRAW_BASE: u16 = 1;

