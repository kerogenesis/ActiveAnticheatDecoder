fn shared_slot(name: &str) -> Option<usize> {
    SHARED.iter().position(|shared| *shared == name)
}

fn main() {
    println!("cargo:rerun-if-changed=build.rs");

    // The DLL product with its /EXPORT overlay is x86-only;
    // other targets still get compiling stubs.
    if env::var("CARGO_CFG_TARGET_ARCH").as_deref() == Ok("x86") {
        emit_exports();
    } else {
        println!("cargo:warning=aa_proxy exports support x86 only");
    }
    render_stubs();
}

/// Alias every supported name onto its stub via linker /EXPORT.
/// x86 stdcall symbols are decorated as _Name@0.
fn emit_exports() {
    let decorated_name = |stub: &str| format!("_{stub}@0");

    let targets: &[(&[(&str, u16)], u16)] =
        &[(DDRAW, DDRAW_BASE), (XINPUT, XINPUT_BASE), (D3D9, D3D9_BASE)];
    for (table, base) in targets {
        for (name, ordinal) in *table {
            assert!(
                *ordinal >= *base && *ordinal <= MAX_ORDINAL,
                "ordinal out of range for {name}"
            );
            if shared_slot(name).is_none() {
                assert!(ordinal - base < NAMED_SLOTS, "slot out of range for {name}");
            }
        }
    }
    let mut seen = BTreeSet::new();
    let mut emit_export = |arg: String| {
        if seen.insert(arg.clone()) {
            println!("cargo:rustc-link-arg=/EXPORT:{arg}");
        }
    };
    for (table, base) in targets {
        for (name, ordinal) in *table {
            match shared_slot(name) {
                Some(index) => {
                    emit_export(format!(
                        "{name}={}",
                        decorated_name(&format!("ForwardShared{index}"))
                    ));
                }
                None => {
                    emit_export(format!(
                        "{name}={}",
                        decorated_name(&format!("Forward{}", ordinal - base))
                    ));
                }
            }
        }
    }
    for ordinal in 1..=MAX_ORDINAL {
        emit_export(format!(
            "{ordinal}={0},@{ordinal},NONAME",
            decorated_name(&format!("ForwardOrdinal{ordinal}"))
        ));
    }
}

fn render_stubs() {
    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR is always set by cargo"));
    let mut stubs = String::from(
        "// Generated by build.rs — do not edit.\n\
         // One patchable stub per forward slot (see build.rs header).\n",
    );
    for slot in 0..NAMED_SLOTS {
        let _ = write!(
            stubs,
            "#[allow(clippy::missing_safety_doc)]\n\
             #[unsafe(no_mangle)]\n\
             pub unsafe extern \"system\" fn Forward{slot}() {{\n\
             \x20   core::hint::black_box({slot}u32);\n\
             }}\n"
        );
    }
    for ordinal in 1..=MAX_ORDINAL {
        let _ = write!(
            stubs,
            "#[allow(clippy::missing_safety_doc)]\n\
             #[unsafe(no_mangle)]\n\
             pub unsafe extern \"system\" fn ForwardOrdinal{ordinal}() {{\n\
             \x20   core::hint::black_box({}u32);\n\
             }}\n",
            10_000 + u32::from(ordinal)
        );
    }
    for (index, _) in SHARED.iter().enumerate() {
        let _ = write!(
            stubs,
            "#[allow(clippy::missing_safety_doc)]\n\
             #[unsafe(no_mangle)]\n\
             pub unsafe extern \"system\" fn ForwardShared{index}() {{\n\
             \x20   core::hint::black_box({}u32);\n\
             }}\n",
            20_000 + index as u32
        );
    }

    let names: Vec<String> = (0..NAMED_SLOTS).map(|slot| format!("Forward{slot}")).collect();
    let _ = writeln!(
        stubs,
        "pub static FORWARD_TABLE: [unsafe extern \"system\" fn(); {NAMED_SLOTS}] = [{}];",
        names.join(", ")
    );
    let ordinals: Vec<String> =
        (1..=MAX_ORDINAL).map(|ordinal| format!("ForwardOrdinal{ordinal}")).collect();
    let _ = writeln!(
        stubs,
        "pub static FORWARD_ORDINAL_TABLE: [unsafe extern \"system\" fn(); {MAX_ORDINAL}] = [{}];",
        ordinals.join(", ")
    );
    let shared: Vec<String> =
        (0..SHARED.len()).map(|index| format!("ForwardShared{index}")).collect();
    let _ = writeln!(
        stubs,
        "pub static FORWARD_SHARED_TABLE: [unsafe extern \"system\" fn(); {}] = [{}];",
        SHARED.len(),
        shared.join(", ")
    );
    fs::write(out_dir.join("stubs.rs"), stubs).expect("cannot write the generated stubs");
}
